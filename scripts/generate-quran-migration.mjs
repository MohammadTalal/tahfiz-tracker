// Generates the Quran reference-data migration from Tanzil metadata.
// The source is parsed as text (never executed). Usage:
//   node scripts/generate-quran-migration.mjs
import { readFileSync, writeFileSync } from "node:fs";

const SOURCE = "data/quran/tanzil-quran-data.txt";
const OUTPUT = "supabase/migrations/20261019000002_quran_reference.sql";

const text = readFileSync(SOURCE, "utf8");

function section(name) {
  const start = text.indexOf(`QuranData.${name} = [`);
  if (start === -1) throw new Error(`Section ${name} not found`);
  const end = text.indexOf("];", start);
  return text.slice(start, end);
}

// [sura, aya] start points, skipping the leading [] and the trailing sentinel.
function startPoints(name) {
  const points = [...section(name).matchAll(/\[(\d+),\s*(\d+)\]/g)].map((m) => [Number(m[1]), Number(m[2])]);
  return points.filter(([sura]) => sura >= 1 && sura <= 114);
}

const str = String.raw`(?:'([^']*)'|"([^"]*)")`;
const suraRow = new RegExp(
  String.raw`\[(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*${str},\s*${str},\s*${str},\s*${str}\]`,
  "g",
);
const surahs = [...section("Sura").matchAll(suraRow)].map((m, i) => ({
  number: i + 1,
  ayahs: Number(m[2]),
  nameArabic: m[5] ?? m[6],
  transliteration: m[7] ?? m[8],
  nameEnglish: m[9] ?? m[10],
  revelation: (m[11] ?? m[12]).toLowerCase(),
}));

const juz = startPoints("Juz");
const hizbQuarters = startPoints("HizbQaurter");
const pages = startPoints("Page");

if (surahs.length !== 114) throw new Error(`Expected 114 surahs, got ${surahs.length}`);
if (juz.length !== 30) throw new Error(`Expected 30 juz, got ${juz.length}`);
if (hizbQuarters.length !== 240) throw new Error(`Expected 240 hizb quarters, got ${hizbQuarters.length}`);
if (pages.length !== 604) throw new Error(`Expected 604 pages, got ${pages.length}`);

const key = (s, a) => s * 1000 + a;
function indexOf(points, s, a) {
  // 1-based number of the last start point at or before (s, a).
  let n = 0;
  for (let i = 0; i < points.length && key(...points[i]) <= key(s, a); i++) n = i + 1;
  return n;
}

const ayahRows = [];
for (const surah of surahs) {
  for (let a = 1; a <= surah.ayahs; a++) {
    ayahRows.push([
      surah.number,
      a,
      indexOf(pages, surah.number, a),
      indexOf(juz, surah.number, a),
      indexOf(hizbQuarters, surah.number, a),
    ]);
  }
}
if (ayahRows.length !== 6236) throw new Error(`Expected 6236 ayahs, got ${ayahRows.length}`);

const q = (s) => `'${s.replaceAll("'", "''")}'`;

const sql = `-- Quran reference data (Hafs, Madani 604-page Mushaf).
-- GENERATED by scripts/generate-quran-migration.mjs from data/quran/tanzil-quran-data.txt.
-- Source: Tanzil Quran Metadata v1.0, (C) 2008-2009 Tanzil.info, CC BY 3.0. Do not edit by hand.

create table public.quran_surahs (
  surah_number smallint primary key check (surah_number between 1 and 114),
  name_arabic text not null,
  name_english text not null,
  transliteration text not null,
  ayah_count smallint not null check (ayah_count > 0),
  revelation_type text not null check (revelation_type in ('meccan', 'medinan'))
);

create table public.quran_ayahs (
  surah_number smallint not null references public.quran_surahs (surah_number),
  ayah_number smallint not null check (ayah_number > 0),
  page_number smallint not null check (page_number between 1 and 604),
  juz_number smallint not null check (juz_number between 1 and 30),
  hizb_quarter smallint not null check (hizb_quarter between 1 and 240),
  primary key (surah_number, ayah_number)
);

create index quran_ayahs_page_idx on public.quran_ayahs (page_number);
create index quran_ayahs_juz_idx on public.quran_ayahs (juz_number);
create index quran_ayahs_hizb_idx on public.quran_ayahs (hizb_quarter);

insert into public.quran_surahs (surah_number, name_arabic, name_english, transliteration, ayah_count, revelation_type) values
${surahs.map((s) => `(${s.number}, ${q(s.nameArabic)}, ${q(s.nameEnglish)}, ${q(s.transliteration)}, ${s.ayahs}, ${q(s.revelation)})`).join(",\n")};

insert into public.quran_ayahs (surah_number, ayah_number, page_number, juz_number, hizb_quarter) values
${ayahRows.map((r) => `(${r.join(",")})`).join(",\n")};

-- Read-only reference data, readable by everyone (including the public site).
alter table public.quran_surahs enable row level security;
alter table public.quran_ayahs enable row level security;

create policy "Quran surahs are readable by everyone" on public.quran_surahs
  for select to anon, authenticated using (true);
create policy "Quran ayahs are readable by everyone" on public.quran_ayahs
  for select to anon, authenticated using (true);

revoke insert, update, delete, truncate on public.quran_surahs, public.quran_ayahs from anon, authenticated;
`;

writeFileSync(OUTPUT, sql);
console.log(`Wrote ${OUTPUT}: ${surahs.length} surahs, ${ayahRows.length} ayahs.`);

// Surah names for the UI (pickers and passage labels), so they need no DB call.
const NAMES_OUTPUT = "src/lib/quran/surah-names.ts";
const ts = `// GENERATED by scripts/generate-quran-migration.mjs from Tanzil metadata (CC BY 3.0). Do not edit.
// Index 0 = surah 1.
export const SURAH_NAMES: readonly { readonly ar: string; readonly en: string }[] = [
${surahs.map((s) => `  { ar: ${JSON.stringify(s.nameArabic)}, en: ${JSON.stringify(s.transliteration)} },`).join("\n")}
];
`;
writeFileSync(NAMES_OUTPUT, ts);
console.log(`Wrote ${NAMES_OUTPUT}.`);

// Where each Mushaf page and juz begins, for picking passages by page or juz.
const DIVISIONS_OUTPUT = "src/lib/quran/divisions-data.ts";
const pairs = (points) => points.map(([s, a]) => `[${s}, ${a}]`).join(", ");
const divisions = `// GENERATED by scripts/generate-quran-migration.mjs from Tanzil metadata (CC BY 3.0). Do not edit.
// [surah, ayah] where each division starts. Index 0 = page/juz 1. Madani Mushaf (604 pages).
export const PAGE_STARTS: readonly (readonly [number, number])[] = [${pairs(pages)}];
export const JUZ_STARTS: readonly (readonly [number, number])[] = [${pairs(juz)}];
`;
writeFileSync(DIVISIONS_OUTPUT, divisions);
console.log(`Wrote ${DIVISIONS_OUTPUT}.`);
